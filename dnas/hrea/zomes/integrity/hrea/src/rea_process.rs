#[derive(Clone, PartialEq)]
#[hdk_entry_helper]
pub struct ReaProcess {
    pub id: Option<ActionHash>,
    pub name: String,
    pub has_beginning: Option<Timestamp>,
    pub has_end: Option<Timestamp>,
    pub before: Option<Timestamp>,
    pub after: Option<Timestamp>,
    pub classified_as: Option<Vec<String>>,
    pub based_on: Option<ActionHash>,
    pub planned_within: Option<ActionHash>,
    pub finished: bool,
    pub in_scope_of: Option<Vec<ActionHash>>,
    pub note: Option<String>,
}

pub fn validate_create_rea_process(
    _action: EntryCreationAction,
    rea_process: ReaProcess,
) -> ExternResult<ValidateCallbackResult> {
    if let Some(action_hash) = rea_process.based_on.clone() {
        let record = must_get_valid_record(action_hash)?;
        let _rea_process_specification: crate::ReaProcessSpecification = record
            .entry()
            .to_app_option()
            .map_err(|e| wasm_error!(e))?
            .ok_or(wasm_error!(WasmErrorInner::Guest(String::from(
                "Dependant action must be accompanied by an entry"
            ))))?;
    }
    if let Some(action_hash) = rea_process.planned_within.clone() {
        let record = must_get_valid_record(action_hash)?;
        let _rea_plan: crate::ReaPlan = record
            .entry()
            .to_app_option()
            .map_err(|e| wasm_error!(e))?
            .ok_or(wasm_error!(WasmErrorInner::Guest(String::from(
                "Dependant action must be accompanied by an entry"
            ))))?;
    }
    // TODO: add the appropriate validation rules
    Ok(ValidateCallbackResult::Valid)
}

